#!/usr/bin/env python3
"""Write .env.prod (the prod profile) and private/cloud.env (tests/copy_db.py) from the SurrealDB
Cloud values in a source env file. Prints only the key names it wrote, never a value.

usage: python3 -I tests/make_prod_env.py [source]   (default .env.example: surreal_endpoint, surreal_password)
The database user, namespace and database are `erp`.
"""
import os, sys
from urllib.parse import quote

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
USER, NS, DB = "erp", "erp", "erp"


def read(path):
    out = {}
    for line in open(path).read().splitlines():
        if "=" in line and not line.lstrip().startswith("#"):
            k, v = line.split("=", 1)
            out[k.strip().lower()] = v.strip().strip('"').strip("'")
    return out


def main():
    src = read(os.path.join(ROOT, sys.argv[1] if len(sys.argv) > 1 else ".env.example"))
    endpoint, password = src["surreal_endpoint"], src["surreal_password"]
    host = endpoint.split("://", 1)[-1].split("/", 1)[0]          # wss://host/rpc, https://host or host
    url = f"wss://{quote(USER, safe='')}:{quote(password, safe='')}@{host}/rpc?auth=database"
    prod = os.path.join(ROOT, ".env.prod")
    with open(prod, "w") as f:
        f.write("# prod profile: SurrealDB Cloud (generated by tests/make_prod_env.py; never committed)\n")
        f.write(f"SECRET_SURREAL_URL={url}\nSURREAL_NS={NS}\nSURREAL_DB={DB}\n")
    os.chmod(prod, 0o600)
    os.makedirs(os.path.join(ROOT, "private"), exist_ok=True)
    cloud = os.path.join(ROOT, "private", "cloud.env")
    with open(cloud, "w") as f:
        f.write(f"SURREAL_ENDPOINT=wss://{host}\nSURREAL_USER={USER}\nSURREAL_PASS={password}\nSURREAL_NS={NS}\nSURREAL_DB={DB}\n")
    os.chmod(cloud, 0o600)
    print("wrote .env.prod: SECRET_SURREAL_URL SURREAL_NS SURREAL_DB")
    print("wrote private/cloud.env: SURREAL_ENDPOINT SURREAL_USER SURREAL_PASS SURREAL_NS SURREAL_DB")


if __name__ == "__main__":
    main()
